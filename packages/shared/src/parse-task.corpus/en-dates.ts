const START_TITLES = ["call John", "renew the license", "send the quote"];

const relative: Row[] = RELATIVE.flatMap(([expr, day, alts = []], i) => {
  const alt = alts.map((d) => ({ day: d }));
  const end = END_TITLES[i % END_TITLES.length];
  const start = START_TITLES[i % START_TITLES.length];
  return [
    [`${end} ${expr}`, end, day, null, { alt }],
    [`${expr} ${start}`, start, day, null, { alt }],
  ];
});

